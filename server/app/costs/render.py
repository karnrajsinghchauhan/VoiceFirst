"""Renders the cost book as Markdown for docs/unit-economics.md and the proposal's cost table."""

from __future__ import annotations

from decimal import Decimal

from app.costs.book import CostBook

START = "<!-- cost-table:start -->"
END = "<!-- cost-table:end -->"


def _rs(paise: Decimal) -> str:
    return f"Rs {(paise / 100).quantize(Decimal('0.0001'))}"


def cost_table(book: CostBook) -> str:
    rows = [
        "| Component | Unit | Unit price (Rs) | Per minute | Basis | Checked |",
        "|---|---|---|---|---|---|",
    ]
    for c in book.components:
        basis = (
            "estimate"
            if c.estimate
            else (f"[{c.source}]({c.source_url})" if c.source_url else c.source)
        )
        rows.append(
            f"| {c.name} | {c.unit} | {c.unit_price} | {_rs(book.per_minute_paise(c.name))} "
            f"| {basis} | {c.checked_at.isoformat()} |"
        )
    a = book.assumptions
    rows += [
        "",
        f"- Per minute, all components: **{_rs(book.total_per_minute_paise())}** (estimate where any line is).",
        f"- Per call at {a.avg_call_minutes} min (estimate): **{_rs(book.per_call_paise())}**.",
        f"- Per resolved contact at a {a.resolution_rate} resolution rate (estimate): "
        f"**{_rs(book.per_resolved_contact_paise())}**.",
        f"- WhatsApp includes GST at {book.gst_rate}. Prices as of {book.as_of.isoformat()}; "
        "re-check before quoting.",
    ]
    return "\n".join(rows)


def comparison_table(book: CostBook) -> str:
    rows = ["| Vendor | Published price | Unit | Source | Checked |", "|---|---|---|---|---|"]
    for c in book.comparison:
        rows.append(
            f"| {c.vendor} | {c.currency} {c.price} | {c.unit} | {c.source_url} "
            f"| {c.checked_at.isoformat()} [CD] re-check |"
        )
    return "\n".join(rows)


def unit_economics_doc(book: CostBook) -> str:
    return "\n".join(
        [
            "# Unit economics",
            "",
            "Generated by `make costs` from `config/costs.yaml`; do not edit by hand.",
            "Every line cites a dated source or is marked estimate. Re-check before quoting.",
            "",
            "## Our cost per minute and per resolved contact",
            "",
            cost_table(book),
            "",
            "## Published list prices of other platforms",
            "",
            "Platform fees only; they exclude telephony and, for some, model and voice costs.",
            "No claim is made beyond these published numbers.",
            "",
            comparison_table(book),
            "",
        ]
    )


def replace_between_markers(text: str, replacement: str) -> str:
    if START not in text or END not in text:
        raise ValueError("cost-table markers missing")
    head, rest = text.split(START, 1)
    _, tail = rest.split(END, 1)
    return f"{head}{START}\n{replacement}\n{END}{tail}"
